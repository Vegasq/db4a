void splash_draw(unsigned frame) {
    static const unsigned char BG[3]    = {  8,  10,  24 };
    static const unsigned char TITLE[3] = {236, 196,  92 };
    static const unsigned char WARN[3]  = {228, 120,  96 };
    static const unsigned char DIM[3]   = {168, 176, 200 };
    static const unsigned char LINK[3]  = {130, 200, 170 };

    for (int y = 0; y < fb_height; y++)
        for (int x = 0; x < fb_width; x++)
            put(x, y, BG);

    centred(28, "DB4A", 5, TITLE);

    int y = 74;
    for (unsigned i = 0; i < sizeof BODY / sizeof BODY[0]; i++, y += 11) {
        if (!*BODY[i]) continue;
        const unsigned char *col = DIM;
        if (i == 1 || i == 2) col = WARN;
        if (i == 9)           col = LINK;
        centred(y, BODY[i], 1, col);
    }

    /* Blink, so it reads as "waiting for you" rather than "stuck". */
    if ((frame / 25) & 1)
        centred(fb_height - 24, "PRESS ANY KEY", 1, DIM);
}

int splash_frames(void) {
    const char *s = cfg("DB4A_SPLASH");
    if (s) { int n = atoi(s); return n < 0 ? 0 : n; }
    return 200;                     /* about four seconds at 49.7 Hz */
}
